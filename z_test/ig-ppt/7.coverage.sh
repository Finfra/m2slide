#!/usr/bin/env bash
# 7.coverage.sh — 커버리지 감사 (Issue369)
#
# 무엇을 지키나
# -------------
# 앞의 러너들은 *"이 덱이 계약대로 돌았는가"* 를 잰다. 이 러너는 **계약이 선언한
# 축을 아무도 재지 않고 있지 않은가** 를 잰다.
#
# 덱이 갈려 있으면 각자 초록불이어도 *"어느 축이 어느 덱에도 없는지"* 는 아무도
# 세지 않는다. 그 사각지대에서 실제로 일이 났다(Issue358):
#
#   표 정렬      `lossy`("소실")로 선언 → 재보니 **보존**된다. 근거 덱의 표가 전부
#                좌측 정렬이라 차이가 드러날 수 없었다
#   테마 밖 폰트 주 러너를 옮기며 축 자체가 **조용히 사라졌다**
#
# 둘 다 **"차이 없음" 과 "차이를 못 봄" 이 구분되지 않은** 것이다.
#
# 판정은 셋이다:
#
#   🔴 검사기가 안 잼   계약은 선언했는데 `scan()` 이 그 요소를 만들지 않는다.
#                       원고에 아무리 많아도 0 이다 — **코드**를 고쳐야 한다
#   ❌ 픽스처에 없음    검사기는 잴 줄 아는데 어느 원고에도 없다 — **원고**를 더한다
#   ⚠️ 한 덱뿐          그 덱을 고치면 축이 사라진다. 차단하지 않고 알린다
#
#   사용: ./z_test/ig-ppt/7.coverage.sh [프로젝트…]
#         인자를 생략하면 회귀 픽스처 4덱을 잰다
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

if [ "$#" -gt 0 ]; then
  DECKS=("$@")
else
  #   기본 5덱 — aTest-all(종합) · aTest(single) · chapter_mode(레이아웃) ·
  #   igTest(인포그래픽) · h3Test(**장 제목이 H3** — Issue412)
  #   ⚠️ h3Test 를 빼면 `title_level_h3` 가 4개짜리 한 덱으로 줄고 `long_cover_title`
  #      은 0 이 된다. 그 상태가 Issue403·406 을 놓친 그때의 픽스처 구성이다
  DECKS=(aTest-all aTest m2Slide_chapter_mode igTest h3Test)
fi

say() { printf '%s\n' "$*"; }
say "════════════════════════════════════════════════════════════"
say " 커버리지 감사 — ${DECKS[*]}"
say "════════════════════════════════════════════════════════════"

python3 lib/pptx/check-coverage.py "${DECKS[@]}"
rc=$?

say ""
if [ "$rc" = "0" ]; then
  say "[7.coverage] 통과 — 미측정 축 0"
else
  say "[7.coverage] 실패 — 위 목록의 축은 **아무도 재지 않는다**"
  say "             계약에서 거두거나, 검사기·픽스처를 고친다."
fi
exit "$rc"
